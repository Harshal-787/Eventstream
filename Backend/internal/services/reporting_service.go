package services

import (
	"bytes"
	"encoding/csv"
	"eventstream/internal/repository"
	"fmt"
	"github.com/jung-kurt/gofpdf"
	"strconv"
)

type ReportingService struct {
	telemetryRepo *repository.TelemetryRepository
	alertRepo     *repository.AlertRepository
	deviceRepo    *repository.DeviceRepo
}

func NewReportingService(telemetryRepo *repository.TelemetryRepository, alertRepo *repository.AlertRepository, deviceRepo *repository.DeviceRepo) *ReportingService {
	return &ReportingService{
		telemetryRepo: telemetryRepo,
		alertRepo:     alertRepo,
		deviceRepo:    deviceRepo,
	}
}

// GenerateTelemetryCSV returns a CSV buffer with telemetry points for a specific device
func (s *ReportingService) GenerateTelemetryCSV(deviceID int) ([]byte, error) {
	telemetry, _, err := s.telemetryRepo.GetHistoricalEvents(1000, 0, map[string]interface{}{
		"device_id": strconv.Itoa(deviceID),
	})
	if err != nil {
		return nil, err
	}

	var buf bytes.Buffer
	writer := csv.NewWriter(&buf)

	// Header
	err = writer.Write([]string{"Timestamp", "DeviceID", "Temperature", "Humidity", "BatteryPct", "SignalStrength"})
	if err != nil {
		return nil, err
	}

	for _, t := range telemetry {
		temp := ""
		if t.Temperature != nil {
			temp = fmt.Sprintf("%.2f", *t.Temperature)
		}
		hum := ""
		if t.Humidity != nil {
			hum = fmt.Sprintf("%.2f", *t.Humidity)
		}

		batt := ""
		sig := ""
		if t.Payload != nil {
			if v, ok := t.Payload["battery_pct"].(float64); ok {
				batt = fmt.Sprintf("%.1f", v)
			}
			if v, ok := t.Payload["signal_strength"].(float64); ok {
				sig = fmt.Sprintf("%.1f", v)
			}
		}

		err = writer.Write([]string{
			t.Timestamp.Format("2006-01-02 15:04:05"),
			strconv.Itoa(t.DeviceID),
			temp,
			hum,
			batt,
			sig,
		})
		if err != nil {
			return nil, err
		}
	}

	writer.Flush()
	return buf.Bytes(), nil
}

// GenerateBuildingHealthPDF returns a PDF buffer summarizing the building's devices and alerts
func (s *ReportingService) GenerateBuildingHealthPDF(orgID int, buildingID int) ([]byte, error) {
	devices, err := s.deviceRepo.GetDevices(&buildingID, "", &orgID)
	if err != nil {
		return nil, err
	}

	pdf := gofpdf.New("P", "mm", "A4", "")
	pdf.AddPage()
	pdf.SetFont("Arial", "B", 16)
	pdf.Cell(40, 10, "Building Health Report")
	pdf.Ln(10)

	pdf.SetFont("Arial", "", 12)
	pdf.Cell(40, 10, fmt.Sprintf("Total Devices: %d", len(devices)))
	pdf.Ln(10)

	// Simple Table Header
	pdf.SetFont("Arial", "B", 12)
	pdf.CellFormat(50, 10, "Device Name", "1", 0, "L", false, 0, "")
	pdf.CellFormat(40, 10, "Status", "1", 0, "L", false, 0, "")
	pdf.CellFormat(40, 10, "Battery", "1", 0, "L", false, 0, "")
	pdf.CellFormat(50, 10, "Signal", "1", 0, "L", false, 0, "")
	pdf.Ln(-1)

	// Table Rows
	pdf.SetFont("Arial", "", 10)
	for _, dev := range devices {
		pdf.CellFormat(50, 10, dev.Name, "1", 0, "L", false, 0, "")
		pdf.CellFormat(40, 10, dev.Status, "1", 0, "L", false, 0, "")
		pdf.CellFormat(40, 10, fmt.Sprintf("%.1f%%", dev.BatteryPct), "1", 0, "L", false, 0, "")
		pdf.CellFormat(50, 10, fmt.Sprintf("%.1f dBm", dev.SignalStrength), "1", 0, "L", false, 0, "")
		pdf.Ln(-1)
	}

	pdf.Ln(10)
	pdf.SetFont("Arial", "B", 12)
	pdf.Cell(40, 10, "Generated by EventStream")

	var buf bytes.Buffer
	err = pdf.Output(&buf)
	if err != nil {
		return nil, err
	}

	return buf.Bytes(), nil
}
