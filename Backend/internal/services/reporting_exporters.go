package services

import (
	"bytes"
	"encoding/csv"
	"time"
	"github.com/jung-kurt/gofpdf"
	"github.com/xuri/excelize/v2"
)

// ReportData represents tabular data for a report
type ReportData struct {
	Title   string
	Headers []string
	Rows    [][]string
}

// ExportCSV exports ReportData to CSV format
func ExportCSV(data ReportData) ([]byte, error) {
	var buf bytes.Buffer
	writer := csv.NewWriter(&buf)

	if err := writer.Write(data.Headers); err != nil {
		return nil, err
	}

	for _, row := range data.Rows {
		if err := writer.Write(row); err != nil {
			return nil, err
		}
	}

	writer.Flush()
	return buf.Bytes(), nil
}

// ExportPDF exports ReportData to PDF format
func ExportPDF(data ReportData) ([]byte, error) {
	pdf := gofpdf.New("L", "mm", "A4", "") // Landscape for wide tables
	pdf.AddPage()
	pdf.SetFont("Arial", "B", 16)
	pdf.Cell(40, 10, data.Title)
	pdf.Ln(8)
	
	pdf.SetFont("Arial", "I", 10)
	pdf.Cell(40, 6, "Generated at: " + time.Now().Format(time.RFC1123))
	pdf.Ln(10)

	// Calculate column widths based on page width
	// A4 Landscape is ~297mm. Leave 20mm margins = 257mm available.
	pageWidth := 257.0
	colWidth := pageWidth
	if len(data.Headers) > 0 {
		colWidth = pageWidth / float64(len(data.Headers))
	}

	pdf.SetFont("Arial", "B", 10)
	for _, h := range data.Headers {
		pdf.CellFormat(colWidth, 10, h, "1", 0, "L", false, 0, "")
	}
	pdf.Ln(-1)

	pdf.SetFont("Arial", "", 9)
	for _, row := range data.Rows {
		for _, cell := range row {
			// Basic truncation or just let it overflow for now
			txt := cell
			if len(txt) > 50 {
				txt = txt[:47] + "..."
			}
			pdf.CellFormat(colWidth, 8, txt, "1", 0, "L", false, 0, "")
		}
		pdf.Ln(-1)
	}

	pdf.Ln(10)
	pdf.SetFont("Arial", "I", 10)
	pdf.Cell(40, 10, "Generated by EventStream")

	var buf bytes.Buffer
	err := pdf.Output(&buf)
	if err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// ExportExcel exports ReportData to Excel format
func ExportExcel(data ReportData) ([]byte, error) {
	f := excelize.NewFile()
	sheet := "Sheet1"
	f.SetSheetName("Sheet1", sheet)

	// Write Headers
	for i, h := range data.Headers {
		cell, _ := excelize.CoordinatesToCellName(i+1, 1)
		f.SetCellValue(sheet, cell, h)
	}

	// Write Rows
	for rowIdx, row := range data.Rows {
		for colIdx, cellVal := range row {
			cell, _ := excelize.CoordinatesToCellName(colIdx+1, rowIdx+2)
			f.SetCellValue(sheet, cell, cellVal)
		}
	}

	// Apply some bold styling to header
	style, err := f.NewStyle(&excelize.Style{
		Font: &excelize.Font{Bold: true},
	})
	if err == nil {
		f.SetRowStyle(sheet, 1, 1, style)
	}

	var buf bytes.Buffer
	if err := f.Write(&buf); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}
